"""Stage A forward-walk backtest for PRO MODE (detect_quick_signal_pro,
quick_scalp_signal.py's structure-first redesign, 2026-11-11).

Unlike the retroactive-replay backtests used elsewhere in this project
(e.g. backtest_vah_gate.py), PRO MODE changes which signals exist at all,
not just filters an already-fired signal set -- so it can't be validated
by re-filtering quick_scalp_predictions.db's logged rows (those were all
generated by the OLD delta-first trigger). This script instead walks
FORWARD through real historical candles and evaluates the new
structure-first gate directly at each historical point, generating its
own fresh candidate-signal set.

SIMPLIFICATION (v1, flagged): `oi_confirms_reversal`/`funding_confirms_*`
are NOT historically evaluated here -- fetching real historical OI/funding
for every one of potentially thousands of walk-forward points is a lot of
extra complexity for a first pass. Both default to their own None-safe
"pass" (counted as confirming) at every point, same as when live data is
genuinely unavailable. This means the confluence score here is missing 2
of its 8 components (oi_not_fresh, funding always score 1) -- treat
results as a read on the STRUCTURE+FLOW core of the design, not the full
scoring scheme. Re-run with real historical OI/funding before trusting
this enough to build Stage B/Phase 4 on top of it.
"""

import json
import sys
import time
import urllib.request
from collections import defaultdict

sys.path.insert(0, __file__.rsplit("/", 1)[0])

from breakout_patterns import breakout_lean, next_key_level

import quick_scalp_signal as q

FUTURES_API = "https://fapi.binance.com"

DEFAULT_SYMBOLS = [
    "BTCUSDT", "ETHUSDT", "SOLUSDT", "XRPUSDT", "BNBUSDT",
    "LTCUSDT", "AVAXUSDT", "LINKUSDT", "ARBUSDT", "INJUSDT",
]
BACKTEST_DAYS = 3
OUTCOME_HORIZON_SECONDS = 3600  # 1h, matches quick_scalp_outcomes.py's longest horizon
RISE_THRESHOLD_PCT = 0.3  # matches quick_scalp_outcomes.RISE_THRESHOLD_PCT


def _fetch_range(symbol, interval, start_ms, end_ms):
    """Paginated historical klines over [start_ms, end_ms] -- Binance caps
    a single call at 1500 candles, so a multi-day 1m pull needs several
    requests."""
    out = []
    cursor = start_ms
    while cursor < end_ms:
        url = (f"{FUTURES_API}/fapi/v1/klines?symbol={symbol}&interval={interval}"
               f"&startTime={cursor}&endTime={end_ms}&limit=1500")
        try:
            raw = json.loads(urllib.request.urlopen(url, timeout=15).read())
        except Exception as e:
            print(f"  fetch failed {symbol} {interval}: {e}")
            break
        if not raw:
            break
        out.extend(raw)
        last_open = raw[-1][0]
        if last_open <= cursor:
            break
        cursor = last_open + 1
        time.sleep(0.05)
    return out


def _parse(raw):
    return [
        {
            "open_time": k[0], "open": float(k[1]), "high": float(k[2]),
            "low": float(k[3]), "close": float(k[4]), "volume": float(k[5]),
            "taker_buy_volume": float(k[9]), "trade_count": int(k[8]),
        }
        for k in raw
    ]


def _delta_at(candles_1m, idx, window_minutes=q.QUICK_DELTA_WINDOW_MINUTES):
    """Rolling delta ending at candles_1m[idx] (inclusive), using only
    data up to that point -- no look-ahead."""
    start = idx - window_minutes + 1
    if start < 0:
        return None, 0
    window = candles_1m[start:idx + 1]
    total_volume = sum(c["volume"] for c in window)
    total_buy = sum(c["taker_buy_volume"] for c in window)
    trade_count = sum(c["trade_count"] for c in window)
    if total_volume <= 0:
        return None, trade_count
    return (2 * total_buy - total_volume) / total_volume, trade_count


def _wall_at(candles_15m, idx, is_long):
    """next_key_level using only 15m candles up to idx (inclusive)."""
    window = candles_15m[:idx + 1]
    if len(window) < 20:
        return None
    return next_key_level(window, is_long)


def _breakout_lean_at(candles_15m, idx):
    window = candles_15m[:idx + 1]
    if len(window) < 20:
        return None
    return breakout_lean(window)


def walk_symbol(symbol, days=BACKTEST_DAYS):
    end_ms = int(time.time() * 1000)
    start_ms = end_ms - days * 24 * 3600 * 1000
    print(f"Fetching {symbol}: 1m/15m/1h over {days}d...")
    candles_1m = _parse(_fetch_range(symbol, "1m", start_ms, end_ms))
    candles_15m = _parse(_fetch_range(symbol, "15m", start_ms, end_ms))
    candles_1h = _parse(_fetch_range(symbol, "1h", start_ms, end_ms))
    if len(candles_1m) < 100 or len(candles_15m) < 30:
        print(f"  insufficient data for {symbol}, skipping")
        return []

    # index 1h candles by open_time for quick lookup per 15m boundary
    h1_by_time = {c["open_time"]: i for i, c in enumerate(candles_1h)}
    h1_times_sorted = sorted(h1_by_time.keys())

    def h1_index_at_or_before(ts):
        # binary-search-free linear scan is fine at this data size
        best = None
        for t in h1_times_sorted:
            if t <= ts:
                best = h1_by_time[t]
            else:
                break
        return best

    candidates = []
    m1_idx_by_time = {c["open_time"]: i for i, c in enumerate(candles_1m)}

    for i15, c15 in enumerate(candles_15m):
        if i15 < q.QUICK_CANDLE_FETCH_LIMIT:
            continue
        ts = c15["open_time"]
        m1_idx = m1_idx_by_time.get(ts)
        if m1_idx is None:
            continue
        delta_pct, trade_count = _delta_at(candles_1m, m1_idx)
        if delta_pct is None or trade_count < q.QUICK_DELTA_MIN_TRADE_COUNT:
            continue
        push_is_long = delta_pct > 0
        is_long = not push_is_long

        wall = _wall_at(candles_15m, i15, push_is_long)
        if wall is None:
            continue
        close = c15["close"]
        if close <= 0:
            continue
        distance_pct = abs(wall - close) / close * 100
        if distance_pct > q.QUICK_PRO_WALL_MAX_DISTANCE_PCT:
            continue
        lean = _breakout_lean_at(candles_15m, i15)
        if lean is not None and (lean["direction"] == "bullish") == push_is_long:
            continue

        window_15m = candles_15m[max(0, i15 - q.QUICK_CANDLE_FETCH_LIMIT + 1):i15 + 1]
        momentum_ok = q._quick_momentum_confirms(push_is_long, window_15m)

        # oi/funding not historically evaluated here (see module docstring) -- pass
        oi_ok, funding_ok, mid_ok = True, True, True

        score, components = q._quick_confluence_score(
            delta_pct, wall, close, momentum_ok, oi_ok, funding_ok, mid_ok,
        )
        if score < q.QUICK_PRO_SCORE_FLOOR:
            continue

        outcome_ts = ts + OUTCOME_HORIZON_SECONDS * 1000
        future = [c for c in candles_15m if c["open_time"] >= outcome_ts]
        if not future:
            continue  # too recent to resolve yet
        outcome_close = future[0]["close"]
        return_pct = (outcome_close - close) / close * 100
        signed_fade_return = return_pct if is_long else -return_pct
        fade_hit = 1 if signed_fade_return >= RISE_THRESHOLD_PCT else 0

        candidates.append({
            "symbol": symbol, "time": ts, "is_long": is_long, "score": score,
            "distance_pct": distance_pct, "signed_fade_return": signed_fade_return,
            "fade_hit": fade_hit, "components": components,
        })

    return candidates


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--days", type=int, default=BACKTEST_DAYS)
    parser.add_argument("--symbols", nargs="*", default=DEFAULT_SYMBOLS)
    args = parser.parse_args()

    all_candidates = []
    for sym in args.symbols:
        all_candidates.extend(walk_symbol(sym, days=args.days))

    n = len(all_candidates)
    print(f"\n=== PRO MODE Stage A forward-walk backtest ({args.days}d, {len(args.symbols)} symbols) ===")
    print(f"Total candidate signals: {n} ({n / args.days:.1f}/day across {len(args.symbols)} symbols)")
    if n == 0:
        print("No candidates generated -- either genuinely too strict, or a bug. Check QUICK_PRO_SCORE_FLOOR/WALL_MAX_DISTANCE_PCT.")
        sys.exit(0)

    hit_rate = sum(c["fade_hit"] for c in all_candidates) / n
    avg_return = sum(c["signed_fade_return"] for c in all_candidates) / n
    print(f"Overall fade-hit rate: {hit_rate:.1%}  avg signed return: {avg_return:+.3f}%")

    by_symbol = defaultdict(list)
    for c in all_candidates:
        by_symbol[c["symbol"]].append(c)
    print("\n-- by symbol --")
    for sym, rows in sorted(by_symbol.items()):
        rn = len(rows)
        rh = sum(r["fade_hit"] for r in rows) / rn
        print(f"  {sym:10} n={rn:3} fade_hit={rh:.1%}")

    by_score = defaultdict(list)
    for c in all_candidates:
        by_score[c["score"]].append(c)
    print("\n-- by score --")
    for score in sorted(by_score):
        rows = by_score[score]
        rn = len(rows)
        rh = sum(r["fade_hit"] for r in rows) / rn
        print(f"  score={score:2} n={rn:3} fade_hit={rh:.1%}")

    print("\n-- by individual component (0 vs >=1) --")
    component_names = list(all_candidates[0]["components"].keys())
    for comp in component_names:
        on = [c for c in all_candidates if c["components"][comp] >= 1]
        off = [c for c in all_candidates if c["components"][comp] == 0]
        on_rate = sum(c["fade_hit"] for c in on) / len(on) if on else None
        off_rate = sum(c["fade_hit"] for c in off) / len(off) if off else None
        on_s = f"{on_rate:.1%}" if on_rate is not None else "n/a"
        off_s = f"{off_rate:.1%}" if off_rate is not None else "n/a"
        print(f"  {comp:20} on: n={len(on):3} hit={on_s}   off: n={len(off):3} hit={off_s}")

    import pickle
    with open("/tmp/pro_mode_backtest_candidates.pkl", "wb") as f:
        pickle.dump(all_candidates, f)
